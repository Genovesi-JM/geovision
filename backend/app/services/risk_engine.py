# ============ RULE DEFINITIONS ============


class RuleEngine:
    """Base class for sector-specific rule engines."""

    def __init__(self, sector: SectorType):
        self.sector = sector
        self.rules = []
        self.required_fields: tuple[str, ...] = ()

    def evaluate(self, data: Dict[str, Any]) -> List[RuleResult]:
        """Evaluate all rules against input data."""
        results = []
        for rule in self.rules:
            try:
                result = rule(data)
                results.append(result)
            except Exception as exc:
                logger.warning("Risk rule evaluation failed: %s", type(exc).__name__)
                raise RiskEvidenceError(
                    f"Risk rule '{rule.__name__}' could not evaluate supplied evidence"
                ) from exc
        return results


