# ============ RISK ASSESSMENT SERVICE ============


class RiskEngine:
    """
    Main risk assessment engine.

    Evaluates sector-specific rules and generates risk scores and alerts.
    """

    SECTOR_ENGINES = {
        SectorType.MINING: MiningRuleEngine,
        SectorType.CONSTRUCTION_INFRASTRUCTURE: InfrastructureRuleEngine,
        # Add further public sectors only with explicit, reviewed rule packs.
    }

    RISK_THRESHOLDS = {
        RiskLevel.LOW: 25,
        RiskLevel.MEDIUM: 50,
        RiskLevel.HIGH: 75,
        RiskLevel.CRITICAL: 100,
    }

    EVIDENCE_BOUNDS = {
        SectorType.MINING: {
            "tailings_level_pct": (0, 100, False),
            "terrain_displacement_mm": (0, None, False),
            "esg_score": (0, 100, False),
            "dust_concentration_ppm": (0, None, False),
            "water_quality_index": (0, 100, False),
            "extraction_efficiency_pct": (0, 100, False),
        },
        SectorType.CONSTRUCTION_INFRASTRUCTURE: {
            "structural_health_index": (0, 100, False),
            "timeline_delay_days": (0, None, False),
            "budget_overrun_pct": (0, None, False),
            "safety_incidents_30d": (0, None, True),
            "material_quality_pass_rate": (0, 100, False),
        },
    }

    def __init__(self):
        self.engines = {
            sector: engine_class()
            for sector, engine_class in self.SECTOR_ENGINES.items()
        }

    def _score_to_level(self, score: float) -> RiskLevel:
        """Convert numeric score to risk level."""
        if score >= 75:
            return RiskLevel.CRITICAL
        elif score >= 50:
            return RiskLevel.HIGH
        elif score >= 25:
            return RiskLevel.MEDIUM
        return RiskLevel.LOW

    def _generate_recommendations(
        self, sector: SectorType, triggered_rules: List[RuleResult]
    ) -> List[str]:
        """Generate recommendations based on triggered rules."""
        recommendations = []

        for rule in triggered_rules:
            if rule.severity == AlertSeverity.CRITICAL:
                recommendations.append(f"URGENT: Address {rule.rule_name} immediately")
            elif rule.severity == AlertSeverity.ERROR:
                recommendations.append(f"Review {rule.rule_name} within 24 hours")
            elif rule.severity == AlertSeverity.WARNING:
                recommendations.append(f"Monitor {rule.rule_name}")

        # Add sector-specific recommendations
        if sector == SectorType.MINING:
            if any(
                r.rule_id.startswith("mining_tailings") and r.triggered
                for r in triggered_rules
            ):
                recommendations.append("Schedule tailings capacity expansion review")
            if any(
                r.rule_id.startswith("mining_displacement") and r.triggered
                for r in triggered_rules
            ):
                recommendations.append("Conduct geotechnical stability assessment")

        elif sector == SectorType.CONSTRUCTION_INFRASTRUCTURE:
            if any(
                r.rule_id.startswith("infra_delay") and r.triggered
                for r in triggered_rules
            ):
                recommendations.append("Review critical path and resource allocation")
            if any(
                r.rule_id.startswith("infra_budget") and r.triggered
                for r in triggered_rules
            ):
                recommendations.append("Conduct cost variance analysis")

        return recommendations[:5]  # Limit to top 5

    def _generate_alerts(
        self, site_id: str, sector: SectorType, triggered_rules: List[RuleResult]
    ) -> List[RiskAlert]:
        """Generate alerts from triggered rules."""
        import uuid

        alerts = []

        for rule in triggered_rules:
            alert = RiskAlert(
                id=str(uuid.uuid4()),
                title=rule.rule_name,
                message=rule.message,
                severity=rule.severity,
                sector=sector,
                source="risk_engine",
                metric_name=rule.rule_id,
                metric_value=rule.data.get("value"),
                threshold=rule.data.get("threshold"),
                recommendation=None,
            )
            alerts.append(alert)

        return alerts

    def assess(
        self, site_id: str, sector: SectorType, data: Dict[str, Any]
    ) -> RiskAssessmentResult:
        """
        Run risk assessment for a site.

        Args:
            site_id: Site identifier
            sector: Sector type
            data: Sensor/metric data for evaluation

        Returns:
            Complete risk assessment result
        """
        import uuid

        # Get sector engine
        engine = self.engines.get(sector)
        if not engine:
            raise RiskEngineNotConfiguredError(
                f"Risk rules are not configured for sector: {sector.value}"
            )

        missing = [field for field in engine.required_fields if data.get(field) is None]
        if missing:
            raise RiskEvidenceError(
                "Risk assessment requires all rule-pack measurements; missing: "
                + ", ".join(missing)
            )
        invalid = [
            field
            for field in engine.required_fields
            if isinstance(data[field], bool)
            or not isinstance(data[field], (int, float))
            or not math.isfinite(float(data[field]))
        ]
        if invalid:
            raise RiskEvidenceError(
                "Risk assessment measurements must be finite numbers; invalid: "
                + ", ".join(invalid)
            )
        out_of_range: list[str] = []
        for metric_name, (minimum, maximum, integer_only) in self.EVIDENCE_BOUNDS[
            sector
        ].items():
            numeric_value = float(data[metric_name])
            if (
                numeric_value < minimum
                or (maximum is not None and numeric_value > maximum)
                or (integer_only and not numeric_value.is_integer())
            ):
                out_of_range.append(metric_name)
        if out_of_range:
            raise RiskEvidenceError(
                "Risk assessment measurements are outside their valid domain: "
                + ", ".join(out_of_range)
            )

        # Evaluate rules
        rule_results = engine.evaluate(data)
        triggered = [r for r in rule_results if r.triggered]

        # Calculate score (capped at 100)
        risk_score = min(100, sum(r.score_contribution for r in triggered))
        risk_level = self._score_to_level(risk_score)

        # Generate outputs
        alerts = self._generate_alerts(site_id, sector, triggered)
        recommendations = self._generate_recommendations(sector, triggered)

        return RiskAssessmentResult(
            assessment_id=str(uuid.uuid4()),
            site_id=site_id,
            sector=sector,
            risk_score=risk_score,
            risk_level=risk_level,
            triggered_rules=triggered,
            alerts=alerts,
            recommendations=recommendations,
            input_data=data,
        )


# Singleton instance
_risk_engine: Optional[RiskEngine] = None


def get_risk_engine() -> RiskEngine:
    """Get or create risk engine instance."""
    global _risk_engine
    if _risk_engine is None:
        _risk_engine = RiskEngine()
    return _risk_engine


